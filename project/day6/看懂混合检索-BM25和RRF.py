print("RRF 全称 Reciprocal Rank Fusion。")
print("中文叫「倒数排名融合」，人话：")
print("  每篇文档的得分 = 它在各路里名次的倒数和，名次越靠前，得的那一份越大。\n")
print("  公式：score(文档) = Σ [ 1 / (k + 名次) ]     名次从 1 开始，k 一般取 60\n")

vec_pos = {k: i for i, (k, _) in enumerate(vec_rank, start=1)}
bm_pos = {k: i for i, (k, _) in enumerate(bm_rank, start=1)}

