def tokenize(text: str) -> list[str]:
    """把一句话切成「词」。中文没空格，这里用了个土办法：
       英文/数字整体当一个词（XR-2000 → xr、2000），
       中文按单字 + 相邻两字（"保修" → 保 / 修 / 保修），保证能抓到两字词。
    """
    text = text.lower() # 转小写，保证 XR 和 xr 算同一个词
    latin = re.findall(r"[a-z0-9]+", text) # xr, 2000, ai, 500
    # re是py自带的正则模块。import引入
    # findall 找到所有匹配的，并返回列表
    # [a-z0-9]+  ['xr', '2000', 'ai', '500'] ← 连着的算一个词
    # re.findall(r"[a-z0-9]+", text) — 正则规则 [a-z0-9]+ 匹配「小写字母或数字连续出现 1 次以上」。
    # + 是关键：xr-2000 中 - 不在字符集里，当分隔符把两端断开 → ['xr', '2000', 'ai', '500']。+只拿到连续字符
    # r"..." 原始字符串，让 \ 不被 Python 提前转义。
    han = re.findall(r"[\u4e00-\u9fff]", text) # 找到每个汉字一个字
    # \u4e00~\u9fff 是 Unicode 基本汉字区。没写 +，所以每个汉字自成一词 → ['坏','了','怎','么','保','修','扩','图','次']。
    bigram = [han[i] + han[i + 1] for i in range(len(han) - 1)]  # 相邻两字拼接成一组
    # 拿到类似：['坏了','了怎','怎么','么保','保修','修扩','扩图','图次']（len=8）
    return latin + han + bigram # 三列拼接返回
    # latin + han + bigram 是列表拼接不是加法，结果约 21 个词，含重复。
    # 重复是故意的：看懂混合检索-BM25和RRF.py:116 里 toks.count(t) 要数 tf（词频），重复次数就是频次


TOKENS = {k: tokenize(v) for k, v in DOCS.items()}
N = len(DOCS)
K1, B = 1.5, 0.75          # BM25 的两个行业默认参数，不用改也够用
AVG_LEN = sum(len(t) for t in TOKENS.values()) / N


def bm25_scores(query: str) -> dict:
    qt = tokenize(query) # ← 查询也切词
    idf = {}
    for t in set(qt): # ← set 去重：每个词只算一次稀有度
        df = sum(1 for toks in TOKENS.values() if t in toks)     # 含这个词的文档数（文档频率）
        # 遍历TOKEN.values()，如果toks内有t，就产出一个1，最后得到一共有几个1 -> 给我一个词t，数一数文档内有几个t
        idf[t] = math.log((N - df + 0.5) / (df + 0.5) + 1)       # 越稀有 → 越大
    out = {}
    for k, toks in TOKENS.items():  # ← 第二段：逐篇文档打分
        total = 0.0
        for t in set(qt):
            tf = toks.count(t)                                   # 本词在本篇出现几次
            if tf == 0:
                continue
            total += idf[t] * (tf * (K1 + 1)) / (tf + K1 * (1 - B + B * len(toks) / AVG_LEN))
            # 总分 = Σ 每个词的  稀有度 IDF × 饱和命中量 × 长度折扣 
        out[k] = total
    return out


