# 第 4 步：RRF —— 怎么把两路名次合起来（用问题1 演示）
# 拿到BM25的分数后，先转化为名次，转为名次之后BM25分数就可以丢弃了。然后供给RRF使用
# 向量检索那边同样如此：先算相似度分，排序得到名次，再把分数丢掉。两路各自只交出一份「排名表」，不交分数。
