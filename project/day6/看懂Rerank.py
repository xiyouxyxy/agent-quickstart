# 第 3 步：交叉编码器 —— 凭什么准
# ==========================================================================
print("=" * 76)
print("第 3 步：交叉编码器（cross-encoder，交叉编码器）—— 「拼在一起，逐字对看」")
print("=" * 76)
print("  做法：把「问题」和「一篇文档」拼成一条输入，中间加个分隔符：\n")
